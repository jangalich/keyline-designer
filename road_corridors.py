"""
road_corridors.py

Computes suggested road corridor geometry from the DEM, for properties
that lack existing farm road/access data — this REPLACES having Claude
infer a plausible-sounding corridor in prose during report generation
(report_generator.py's Farm Roads step used to do exactly that, with an
explicit "no dedicated access data" disclaimer). Same pattern as
water_candidate_zones.py and solar_suitability.py: the backend computes
real geometry, Claude narrates from the result.

Candidates are generated by routing a least-cost path (road_cost_path.py
— see that module for the cost-raster/Dijkstra core itself, imported and
used here, not reimplemented) across a per-cell traversal-cost grid built
from this property's own slope, exclusion, and production-zone data:

  SOURCE CELLS: the DEM's own row/col extent is split into a fixed
  ROAD_SOURCE_GRID_ROWS x ROAD_SOURCE_GRID_COLS grid of quadrants
  (_select_quadrant_source_cells()), and the single eligible cell nearest
  each quadrant's own center becomes that quadrant's source — up to 4
  independent routing attempts spread across the property, rather than
  one arbitrary starting point or an exhaustive search from everywhere
  eligible. A quadrant with no eligible ground at all is skipped, not
  forced to contribute a source from somewhere else.

  DESTINATION CELLS: a two-tier search (_select_destination_cells()) —
  eligible cells near real, existing road frontage first
  (ROAD_DESTINATION_SEARCH_METERS), falling back to eligible cells near
  the parcel boundary itself (ROAD_BOUNDARY_ADJACENT_METERS) whenever no
  road data is available, or nothing eligible falls within the first
  tier's search radius. Every destination candidate is passed into a
  single least_cost_path() call together — Dijkstra's own ascending-cost
  pop order already finds whichever one is cheapest, so this never needs
  to run once per destination candidate.

  ROUTING: one least_cost_path() call PER SOURCE CELL (not one combined
  multi-source call across all four) against every destination candidate
  at once — each quadrant's source produces its own independent
  candidate route, rather than every quadrant collapsing onto whichever
  single path happens to be cheapest overall. Up to 4 candidates result,
  one per quadrant that had eligible ground to start from.

  RANKING: candidates are ranked by ascending total_cost
  (least_cost_path()'s own Dijkstra path cost — the running sum of grade-
  and production-penalized edge weights along the route), not a separate
  weighted composite score. suitability_score is a simple normalization
  of that same total_cost against the most expensive candidate in this
  batch, kept only for continuity with existing report/render code that
  expects a 0-100 score to display.

Constraint stack, split cleanly into HARD exclusions (baked into
cost_raster as np.inf — a candidate genuinely cannot be routed through
these at all) and a SOFT cost preference (baked into cost_raster as a
finite penalty a route can still choose to pay):
  - HARD exclusions:
      - outside the single SELECTED water-system candidate zone
        (water_suitability.fetch_and_select_optimal_water_zone() — the
        one rank-1 zone this property's own water-suitability scoring
        actually picked, not every unscored candidate zone
        water_candidate_zones.py generates), buffered wider — routing on
        the uphill side of a pond/dam, not across its face or catchment
        inlet
      - outside floodplain/hydric ground, sourced from real NHD stream/
        water-body buffers + SSURGO hydric soil polygons (NOT inferred
        from DEM elevation alone) — falls back to a buffer around
        delineated valley lines only if neither NHD nor SSURGO data is
        reachable, and flags that fallback explicitly in confidence_notes
      - within a pinned maximum grade (MAX_ROAD_GRADE_PCT) — and, via
        road_cost_path.build_cost_raster()'s own quadratic grade penalty,
        a route that stays comfortably under that ceiling is preferred
        over one that merely clears it
  - SOFT cost preference:
      - production zones — a flat per-cell cost penalty
        (road_cost_path.PRODUCTION_CROSSING_COST_PENALTY), not an
        exclusion. A road is a thin linear feature, not a large permanent
        land claim the way a pond/dam site is, so crossing production
        land is a real, valid routing option (same reasoning as
        solar_suitability.py's own production-zone-proximity redesign)
        when the alternative is a meaningfully longer detour. This was a
        hard exclusion in an earlier version of this module; with
        production_area.py's own slope ceiling now at 20%, one large
        production zone can cover most of a property's gentle ground, and
        hard-excluding it left nowhere for a corridor to exist at all
        (confirmed live: zero corridor candidates with the exclusion,
        real candidates once it was removed).

Erosion-prone soil (SSURGO K-factor) is deliberately NOT part of this
module's constraint stack at all, hard or soft — this pipeline's own
KSOP (Keyline Scale of Permanence) ordering puts Soil at step 8, well
below Farm Roads at step 4; scoring a step-4 feature against step-8 data
inverted that ordering, so the erosion-avoidance preference this module
used to carry has been removed outright, not just softened further.

Corridor anchoring (connecting the near-boundary end of a generated
corridor to the property line) anchors to a real, NAMED mapped existing
road only (farm_roads_data.py, filtered here to drop its "Unnamed road"
fallback entries — an anonymous fetched segment, e.g. an unlabeled
driveway, is not a plausible frontage to claim by name) — the connector
snaps toward the nearest point on that real named road's own frontage,
and properties.anchor_road_name / anchor_status="connected_to_named_road"
report which one. When no named road is reachable nearby, this does NOT
fall back to an arbitrary boundary point — the candidate is kept as-is,
with no connector segment at all, and anchor_status is
"no_named_road_available".

find_candidate_road_corridors() is the pure geometric/scoring core — see
water_candidate_zones.py's and solar_suitability.py's docstrings for why
this split matters (independently testable against a synthetic DEM,
without any of the several real network fetches this feature depends on).
"""

