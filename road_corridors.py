def _build_exclusion_cell_mask(dem: dict, excluded_prepared, boundary_prepared) -> np.ndarray:
    """Per-cell boolean mask (True = excluded), built once by testing
    every valid cell center against the (prepared, unioned) exclusion
    geometry AND against the real parcel boundary — reused across every
    contour band and ridge branch rather than re-testing point-in-polygon
    per band.

    A cell outside boundary_prepared is excluded here the same way an
    excluded-zone cell is — this is what keeps contour-band and ridge-top
    candidates from being generated out of the DEM's buffered area past
    the drawn boundary (dem_data.py fetches ~100m past the parcel on
    purpose; without this, a candidate could be built entirely from
    off-parcel cells). The only geometry that's still allowed to touch/
    reach the boundary line is the single connector segment
    _anchor_to_boundary() adds afterward, when a named road is available
    to anchor to — not something this mask should (or does) affect."""
    array = dem["array"]
    rows, cols = array.shape
    excluded = np.zeros((rows, cols), dtype=bool)

    valid = ~np.isnan(array)
    for r in range(rows):
        for c in range(cols):
            if not valid[r, c]:
                continue
            point = Point(pixel_center_xy(dem, r, c))
            if not boundary_prepared.contains(point):
                excluded[r, c] = True
            elif excluded_prepared is not None and excluded_prepared.contains(point):
                excluded[r, c] = True
    return excluded


def _build_production_cell_mask(dem: dict, production_prepared, boundary_prepared) -> np.ndarray:
    """Per-cell boolean mask (True = cell center falls inside the
    production-zone union) -- same iteration structure as
    _build_exclusion_cell_mask(), reused here as a COST-PENALTY input
    (build_cost_raster()'s production_mask) rather than a hard exclusion:
    crossing production land costs more, it isn't disallowed.

    production_prepared is the (prepared) union of production_areas' own
    render_fill_polygon_utm geometry (see find_candidate_road_corridors()),
    or None if this property has no production zones at all -- in which
    case every cell is simply False. A cell outside boundary_prepared is
    left False here too: off-parcel cells are already hard-excluded via
    excluded_mask/cost_raster regardless of this mask's value for them, so
    there's nothing meaningful to report about their production status."""
    array = dem["array"]
    rows, cols = array.shape
    production_mask = np.zeros((rows, cols), dtype=bool)

    if production_prepared is None:
        return production_mask

    valid = ~np.isnan(array)
    for r in range(rows):
        for c in range(cols):
            if not valid[r, c]:
                continue
            point = Point(pixel_center_xy(dem, r, c))
            if boundary_prepared.contains(point) and production_prepared.contains(point):
                production_mask[r, c] = True
    return production_mask


def _select_quadrant_source_cells(
    dem: dict,
    eligible_mask: np.ndarray,
    boundary_polygon_utm: Polygon,
) -> list[tuple[int, int]]:
    """
    Splits the DEM grid's own row/col extent into a fixed
    ROAD_SOURCE_GRID_ROWS x ROAD_SOURCE_GRID_COLS grid of quadrants and
    returns, for each quadrant that has ANY eligible cell at all, the
    single eligible cell nearest that quadrant's own center (plain row/col
    Euclidean distance -- cheap grid-index arithmetic, no shapely geometry
    needed for this part). A quadrant with zero eligible cells is skipped
    entirely, not forced to contribute a source from somewhere else --
    the same "an honest, possibly-shorter answer beats a forced one"
    pattern every other candidate-generation step in this pipeline
    follows.

    Returns up to ROAD_SOURCE_GRID_ROWS * ROAD_SOURCE_GRID_COLS cells
    (4, by default).

    boundary_polygon_utm is accepted for signature symmetry with
    _select_destination_cells() (which does need it, for its own Tier 2
    fallback) but isn't used here directly: eligible_mask itself already
    reflects the boundary (any off-parcel cell is hard-excluded upstream,
    in _build_exclusion_cell_mask()), so a second boundary check here
    would be redundant.
    """
    rows, cols = eligible_mask.shape
    eligible_rc = np.argwhere(eligible_mask)
    if eligible_rc.size == 0:
        return []

    row_edges = np.linspace(0, rows, ROAD_SOURCE_GRID_ROWS + 1)
    col_edges = np.linspace(0, cols, ROAD_SOURCE_GRID_COLS + 1)

    source_cells = []
    for qr in range(ROAD_SOURCE_GRID_ROWS):
        row_lo, row_hi = row_edges[qr], row_edges[qr + 1]
        center_row = (row_lo + row_hi) / 2.0
        row_in_quadrant = (eligible_rc[:, 0] >= row_lo) & (eligible_rc[:, 0] < row_hi)

        for qc in range(ROAD_SOURCE_GRID_COLS):
            col_lo, col_hi = col_edges[qc], col_edges[qc + 1]
            center_col = (col_lo + col_hi) / 2.0

            in_quadrant = row_in_quadrant & (eligible_rc[:, 1] >= col_lo) & (eligible_rc[:, 1] < col_hi)
            quadrant_cells = eligible_rc[in_quadrant]
            if quadrant_cells.size == 0:
                continue  # no eligible ground in this quadrant -- skip it, not forced

            distances_sq = (quadrant_cells[:, 0] - center_row) ** 2 + (quadrant_cells[:, 1] - center_col) ** 2
            nearest = quadrant_cells[np.argmin(distances_sq)]
            source_cells.append((int(nearest[0]), int(nearest[1])))

    return source_cells


def _select_destination_cells(
    dem: dict,
    eligible_mask: np.ndarray,
    boundary_polygon_utm: Polygon,
    road_union_utm,
) -> list[tuple[int, int]]:
    """
    Two-tier destination search, independent of _anchor_to_boundary()'s
    own (separate, later) anchoring step:

      Tier 1: if road_union_utm is not None, every eligible cell within
      ROAD_DESTINATION_SEARCH_METERS of it -- routing toward real,
      existing road frontage first.

      Tier 2 (fallback): every eligible cell within
      ROAD_BOUNDARY_ADJACENT_METERS of boundary_polygon_utm's own
      exterior ring -- used whenever road_union_utm is None, OR Tier 1
      comes back empty (a named road exists somewhere nearby, but nothing
      eligible actually falls within its search radius -- this falls
      through rather than silently returning zero destinations just
      because Tier 1 was attempted).

    Returns [] if both tiers come back empty (no eligible cell anywhere
    near either a real road or the parcel boundary) -- shouldn't happen on
    a property with any eligible ground reaching its own edge, but a real,
    defensive possibility worth returning honestly rather than raising;
    callers treat this the same way least_cost_path()'s own "no path
    found" None already is handled.
    """
    eligible_rc = np.argwhere(eligible_mask)
    if eligible_rc.size == 0:
        return []

    def _cells_within(target_geometry, distance_meters: float) -> list[tuple[int, int]]:
        search_region = prep(target_geometry.buffer(distance_meters))
        cells = []
        for r, c in eligible_rc:
            r, c = int(r), int(c)
            if search_region.contains(Point(pixel_center_xy(dem, r, c))):
                cells.append((r, c))
        return cells

    if road_union_utm is not None:
        tier1_cells = _cells_within(road_union_utm, ROAD_DESTINATION_SEARCH_METERS)
        if tier1_cells:
            return tier1_cells

    return _cells_within(boundary_polygon_utm.exterior, ROAD_BOUNDARY_ADJACENT_METERS)


AnchorStatus = Literal["connected_to_named_road", "no_named_road_available"]


def _anchor_to_boundary(
    points_xyz: list[tuple[float, float, float]],
    boundary_polygon_utm: Polygon,
    road_union_utm,
    road_features_utm: Optional[list[dict]] = None,
) -> tuple[list[tuple[float, float, float]], AnchorStatus, Optional[str], Optional[float]]:
    """Extends whichever end of the corridor is closer to the property
    boundary with one connecting vertex on the boundary line, snapped to
    the point nearest a real, NAMED mapped road — road_union_utm and
    road_features_utm are already filtered to named roads only by
    _fetch_existing_road_features_utm() before reaching here (see module
    docstring's "Corridor anchoring" section), so a non-None road_union_utm
    always means a genuine, nameable frontage candidate.

    When no named road is nearby (road_union_utm is None), this does NOT
    fall back to an arbitrary boundary point — it returns points_xyz
    completely unchanged, with no connector vertex appended at all. The
    candidate's own interior geometry is still real DEM-derived routing;
    it simply doesn't reach the boundary.

    road_features_utm (optional, each {'name': str, 'line_utm': LineString})
    is used ONLY to report WHICH real road the anchor snapped toward, when
    one is available — passing None still anchors correctly via
    road_union_utm, it just leaves the reported road name generic/absent.

    Returns (points, anchor_status, anchor_road_name, anchor_road_distance_m).
    The last two are None when anchor_status is "no_named_road_available".
    """
    if road_union_utm is None:
        return points_xyz, "no_named_road_available", None, None

    boundary_line = boundary_polygon_utm.boundary
    end_a = Point(points_xyz[0][0], points_xyz[0][1])
    end_b = Point(points_xyz[-1][0], points_xyz[-1][1])

    anchor_at_start = end_a.distance(boundary_line) <= end_b.distance(boundary_line)
    anchor_end = end_a if anchor_at_start else end_b

    nearest_road_point = nearest_points(anchor_end, road_union_utm)[1]
    boundary_anchor_point = nearest_points(nearest_road_point, boundary_line)[1]
    anchor_road_distance_m = float(anchor_end.distance(road_union_utm))
    anchor_road_name = None
    if road_features_utm:
        nearest_feature = min(road_features_utm, key=lambda f: f["line_utm"].distance(anchor_end))
        anchor_road_name = nearest_feature["name"]

    connector_elevation = points_xyz[0][2] if anchor_at_start else points_xyz[-1][2]
    connector = (float(boundary_anchor_point.x), float(boundary_anchor_point.y), connector_elevation)

    extended = [connector] + points_xyz if anchor_at_start else points_xyz + [connector]
    return extended, "connected_to_named_road", anchor_road_name, anchor_road_distance_m


def _grade_stats(points_xyz: list[tuple[float, float, float]]) -> tuple[float, float]:
    grades = []
    for (x1, y1, z1), (x2, y2, z2) in zip(points_xyz, points_xyz[1:]):
        distance = math.hypot(x2 - x1, y2 - y1)
        if distance > 0:
            grades.append(abs(z2 - z1) / distance * 100.0)
    if not grades:
        return 0.0, 0.0
    return float(np.mean(grades)), float(np.std(grades))


