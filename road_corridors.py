def _invert_dem(dem: dict) -> dict:
    return {**dem, "array": -dem["array"]}


def _build_exclusion_cell_mask(dem: dict, excluded_prepared, boundary_prepared) -> np.ndarray:
    """Per-cell boolean mask (True = excluded), built once by testing
    every valid cell center against the (prepared, unioned) exclusion
    geometry AND against the real parcel boundary — reused across every
    contour band and ridge branch rather than re-testing point-in-polygon
    per band.

    A cell outside boundary_prepared is excluded here the same way an
    excluded-zone cell is — this is what keeps contour-band and ridge-top
    candidates from being generated out of the DEM's buffered area past
    the drawn boundary (dem_data.py fetches ~100m past the parcel on
    purpose; without this, a candidate could be built entirely from
    off-parcel cells). The only geometry that's still allowed to touch/
    reach the boundary line is the single connector segment
    _anchor_to_boundary() adds afterward — that's the already-disclosed
    "arbitrary boundary anchor" limitation, not something this mask
    should (or does) affect."""
    array = dem["array"]
    rows, cols = array.shape
    excluded = np.zeros((rows, cols), dtype=bool)

    valid = ~np.isnan(array)
    for r in range(rows):
        for c in range(cols):
            if not valid[r, c]:
                continue
            point = Point(pixel_center_xy(dem, r, c))
            if not boundary_prepared.contains(point):
                excluded[r, c] = True
            elif excluded_prepared is not None and excluded_prepared.contains(point):
                excluded[r, c] = True
    return excluded


def _generate_contour_band_cell_groups(
    dem: dict,
    slope_pct: np.ndarray,
    excluded_mask: np.ndarray,
    max_grade_pct: float,
    band_width_meters: float,
    min_cells: int,
) -> list[list[tuple[int, int]]]:
    """Slices the DEM's elevation range into non-overlapping bands and
    returns every sufficiently-large connected, unexcluded, low-slope
    patch within each band as a raw cell list. A single band can
    legitimately produce more than one patch (e.g. terrain wrapping
    around a hill at the same elevation on two sides)."""
    array = dem["array"]
    valid = ~np.isnan(array)
    low_slope = (~np.isnan(slope_pct)) & (slope_pct <= max_grade_pct)
    eligible_base = valid & low_slope & (~excluded_mask)

    if not np.any(eligible_base):
        return []

    elevations = array[valid]
    min_elev, max_elev = float(np.min(elevations)), float(np.max(elevations))

    groups = []
    band_start = min_elev
    while band_start < max_elev:
        band_end = band_start + band_width_meters
        band_mask = eligible_base & (array >= band_start) & (array < band_end)
        if np.any(band_mask):
            labels, num_components = connected_components(band_mask)
            for component_id in range(num_components):
                cells = [(int(r), int(c)) for r, c in np.argwhere(labels == component_id)]
                if len(cells) >= min_cells:
                    groups.append(cells)
        band_start = band_end

    return groups


def _pca_centerline(
    cells: list[tuple[int, int]], dem: dict, target_point_spacing_m: Optional[float] = None
) -> Optional[list[tuple[float, float, float]]]:
    """Reduces an unordered blob of grid cells to an ordered centerline —
    the direction of greatest spatial variance (PCA on cell centers) is
    treated as the corridor's long axis, cells are binned along that
    axis, and each bin's median perpendicular position becomes one
    ordered path vertex. Returns None for a blob too small or too
    round/compact to represent a linear corridor at all."""
    if len(cells) < 3:
        return None

    array = dem["array"]
    px, py = dem["resolution_meters"]
    if target_point_spacing_m is None:
        target_point_spacing_m = max(px, py) * 2

    utm_xy = np.array([pixel_center_xy(dem, r, c) for r, c in cells])
    elevations = np.array([float(array[r, c]) for r, c in cells])

    centroid = utm_xy.mean(axis=0)
    centered = utm_xy - centroid

    cov = np.cov(centered.T)
    eigvals, eigvecs = np.linalg.eigh(cov)
    principal_axis = eigvecs[:, int(np.argmax(eigvals))]
    perpendicular_axis = np.array([-principal_axis[1], principal_axis[0]])

    projections = centered @ principal_axis
    perp = centered @ perpendicular_axis

    span = float(projections.max() - projections.min())
    if span < target_point_spacing_m:
        return None  # too compact along its own long axis to be a corridor

    num_bins = max(3, int(span / target_point_spacing_m))
    bin_edges = np.linspace(projections.min(), projections.max(), num_bins + 1)
    bin_indices = np.clip(np.digitize(projections, bin_edges[1:-1]), 0, num_bins - 1)

    points = []
    for b in range(num_bins):
        mask = bin_indices == b
        if not np.any(mask):
            continue
        median_perp = float(np.median(perp[mask]))
        median_proj = float(np.median(projections[mask]))
        xy = centroid + median_proj * principal_axis + median_perp * perpendicular_axis
        elevation = float(np.mean(elevations[mask]))
        points.append((float(xy[0]), float(xy[1]), elevation))

    return points if len(points) >= 2 else None


def _contiguous_valid_runs(
    branch_rowcol: list[tuple[int, int]],
    branch_utm_inverted: list[tuple[float, float, float]],
    slope_pct: np.ndarray,
    excluded_mask: np.ndarray,
    max_grade_pct: float,
) -> list[list[tuple[float, float, float]]]:
    """Same contiguous-run pattern as water_candidate_zones.py's
    _runs_of_qualifying_points: walks an already-ordered ridge branch and
    breaks it wherever a point fails the grade or exclusion check,
    keeping runs of at least 2 points. branch_utm_inverted carries the
    INVERTED-DEM elevation (see delineate_valleys() on the negated DEM in
    _generate_ridge_candidates); this negates it back to real elevation
    for the returned points."""
    runs = []
    current: list[tuple[float, float, float]] = []

    for (r, c), (x, y, inverted_elevation) in zip(branch_rowcol, branch_utm_inverted):
        ok = (
            not excluded_mask[r, c]
            and not np.isnan(slope_pct[r, c])
            and slope_pct[r, c] <= max_grade_pct
        )
        if ok:
            current.append((x, y, -inverted_elevation))
        else:
            if len(current) >= 2:
                runs.append(current)
            current = []

    if len(current) >= 2:
        runs.append(current)

    return runs


def _generate_ridge_candidate_runs(
    dem: dict,
    slope_pct: np.ndarray,
    excluded_mask: np.ndarray,
    max_grade_pct: float,
    min_area_acres: float,
    min_primary_area_acres: float,
) -> list[list[tuple[float, float, float]]]:
    """Ridge lines via valley_delineation.delineate_valleys() against an
    inverted DEM (see module docstring), trimmed to grade/exclusion-
    passing contiguous runs."""
    ridges = delineate_valleys(
        _invert_dem(dem),
        min_stream_area_acres=min_area_acres,
        min_primary_valley_area_acres=min_primary_area_acres,
    )

    runs = []
    for ridge in ridges:
        for branch_rowcol, branch_utm in zip(ridge["branches_rowcol"], ridge["branches_utm"]):
            runs.extend(
                _contiguous_valid_runs(branch_rowcol, branch_utm, slope_pct, excluded_mask, max_grade_pct)
            )
    return runs


def _anchor_to_boundary(
    points_xyz: list[tuple[float, float, float]],
    boundary_polygon_utm: Polygon,
    road_union_utm,
    road_features_utm: Optional[list[dict]] = None,
) -> tuple[list[tuple[float, float, float]], bool, Optional[str], Optional[float]]:
    """Extends whichever end of the corridor is closer to the property
    boundary with one connecting vertex on the boundary line — snapped to
    the point nearest a real mapped road if road_union_utm is available
    (a genuine plausible frontage point), otherwise just the nearest
    boundary point (arbitrary, flagged via the returned bool).

    road_features_utm (optional, each {'name': str, 'line_utm': LineString})
    is used ONLY to report WHICH real road the anchor snapped toward, when
    one is available — passing None still anchors correctly via
    road_union_utm, it just leaves the reported road name generic/absent.

    Returns (extended_points, is_arbitrary, anchor_road_name, anchor_road_distance_m).
    The last two are None when anchoring is arbitrary (no real road data).
    """
    boundary_line = boundary_polygon_utm.boundary
    end_a = Point(points_xyz[0][0], points_xyz[0][1])
    end_b = Point(points_xyz[-1][0], points_xyz[-1][1])

    anchor_at_start = end_a.distance(boundary_line) <= end_b.distance(boundary_line)
    anchor_end = end_a if anchor_at_start else end_b

    anchor_road_name = None
    anchor_road_distance_m = None

    if road_union_utm is not None:
        nearest_road_point = nearest_points(anchor_end, road_union_utm)[1]
        boundary_anchor_point = nearest_points(nearest_road_point, boundary_line)[1]
        is_arbitrary = False
        anchor_road_distance_m = float(anchor_end.distance(road_union_utm))
        if road_features_utm:
            nearest_feature = min(road_features_utm, key=lambda f: f["line_utm"].distance(anchor_end))
            anchor_road_name = nearest_feature["name"]
    else:
        boundary_anchor_point = nearest_points(anchor_end, boundary_line)[1]
        is_arbitrary = True

    connector_elevation = points_xyz[0][2] if anchor_at_start else points_xyz[-1][2]
    connector = (float(boundary_anchor_point.x), float(boundary_anchor_point.y), connector_elevation)

    extended = [connector] + points_xyz if anchor_at_start else points_xyz + [connector]
    return extended, is_arbitrary, anchor_road_name, anchor_road_distance_m


def _grade_stats(points_xyz: list[tuple[float, float, float]]) -> tuple[float, float]:
    grades = []
    for (x1, y1, z1), (x2, y2, z2) in zip(points_xyz, points_xyz[1:]):
        distance = math.hypot(x2 - x1, y2 - y1)
        if distance > 0:
            grades.append(abs(z2 - z1) / distance * 100.0)
    if not grades:
        return 0.0, 0.0
    return float(np.mean(grades)), float(np.std(grades))


def _production_avoidance_score(
    line_utm, raw_production_union, reference_meters: float = PRODUCTION_AVOIDANCE_REFERENCE_METERS
) -> float:
    """
    0-1 PREFERENCE score (NOT an exclusion — see module docstring) for how
    much a corridor avoids production zones: 1.0 if it doesn't cross or
    come within reference_meters of any production zone (or none exist on
    this property at all), 0.0 if it actually crosses/touches one, linear
    in between. A production-zone-crossing candidate still gets a real,
    non-zero composite score from its other factors — this only softens
    its RANKING relative to an otherwise-comparable non-crossing
    alternative; it never drops or excludes the candidate.
    """
    if raw_production_union is None or raw_production_union.is_empty:
        return 1.0
    if line_utm.intersects(raw_production_union):
        return 0.0
    return min(1.0, line_utm.distance(raw_production_union) / reference_meters)


def _corridor_score(
    avg_grade_pct: float,
    grade_stddev_pct: float,
    margin_m: float,
    length_m: float,
    longest_length_m: float,
    max_grade_pct: float,
    production_avoidance_score: float,
) -> float:
    grade_score = max(0.0, 1.0 - avg_grade_pct / max_grade_pct)
    consistency_score = max(0.0, 1.0 - grade_stddev_pct / max_grade_pct)
    grade_consistency_score = 0.5 * grade_score + 0.5 * consistency_score

    margin_score = min(1.0, margin_m / EXCLUSION_MARGIN_REFERENCE_METERS)
    length_score = 1.0 - (length_m / longest_length_m) if longest_length_m > 0 else 1.0

    return (
        GRADE_SCORE_WEIGHT * grade_consistency_score
        + EXCLUSION_MARGIN_WEIGHT * margin_score
        + LENGTH_SCORE_WEIGHT * length_score
        + PRODUCTION_AVOIDANCE_SCORE_WEIGHT * production_avoidance_score
    )


def find_candidate_road_corridors(
    dem: dict,
    production_areas: list[dict],
    pond_zones: list[dict],
    boundary_polygon_utm: Polygon,
    hydric_floodplain_union=None,
    erosion_prone_union=None,
    road_union_utm=None,
    road_features_utm: Optional[list[dict]] = None,
    max_grade_pct: float = MAX_ROAD_GRADE_PCT,
    min_corridor_length_meters: float = MIN_CORRIDOR_LENGTH_METERS,
    max_candidates: int = MAX_CANDIDATES,
) -> list[dict]:
    """
    Pure geometric/scoring core — see module docstring for why this takes
    already-computed inputs (production/pond zones, floodplain/erosion
    exclusion unions, optional real-road data for anchoring) rather than
    fetching or delineating anything itself.

    pond_zones is water_candidate_zones.find_candidate_zones()'s own
    output shape (each entry carrying 'polygon_utm'), still HARD-excluded
    (buffered). production_areas is production_area.py's/
    production_suitability.py's own patch shape (each entry carrying
    'polygon_utm') but is NOT a hard exclusion here — see module
    docstring's "SOFT preference" section and _production_avoidance_score().
    hydric_floodplain_union/erosion_prone_union are shapely
    geometries (or None to skip that exclusion) already in dem['crs'],
    both still HARD-excluded.

    road_union_utm is a shapely geometry (or None) of existing real
    roads, used for anchoring (see _anchor_to_boundary) — passing None
    doesn't disable anything here, it just makes every candidate's
    boundary connection point arbitrary rather than road-frontage-based.
    road_features_utm (optional, each {'name': str, 'line_utm': LineString})
    additionally lets an anchored candidate report WHICH real road it
    anchored to (properties.anchor_road_name); omitting it still anchors
    correctly via road_union_utm, it just leaves the road name generic.

    boundary_polygon_utm does double duty: it's both the anchoring target
    (_anchor_to_boundary) AND, via _build_exclusion_cell_mask(), the hard
    limit on which DEM cells contour-band/ridge-top generation can draw
    from at all — the DEM covers ~100m past the drawn boundary on purpose
    (dem_data.py), but a corridor's own candidate geometry must come from
    on-parcel cells only. The single connector segment
    _anchor_to_boundary() adds to reach the boundary line is the one
    already-disclosed exception (see connection_point_is_arbitrary and
    its confidence_notes caveat) — it's added AFTER this exclusion, not
    subject to it.

    Returns up to max_candidates entries, both corridor types ranked
    together, best-first:
        {
            'rank': int,
            'corridor_type': 'contour' | 'ridge',
            'suitability_score': float,      # 0-1
            'avg_grade_pct': float,
            'length_m': float,
            'connection_point_is_arbitrary': bool,
            'anchor_road_name': Optional[str],       # None if anchor is arbitrary or unnamed
            'anchor_road_distance_m': Optional[float],  # None if anchor is arbitrary
            'crosses_production_zone': bool,
            'points_xyz': [(x, y, elevation_m), ...],
            'geometry_wgs84': GeoJSON LineString,
        }
    """
    slope_pct, _aspect_deg = compute_slope_and_aspect(dem["array"], dem["resolution_meters"])

    # Production zones are NOT a hard exclusion here (see module
    # docstring) -- raw_production_union (unbuffered) is kept only for
    # _production_avoidance_score()'s scoring preference and the
    # crosses_production_zone report below, never fed into the exclusion
    # mask that constrains where candidate geometry can be generated from.
    raw_production_union = unary_union([p["polygon_utm"] for p in production_areas]) if production_areas else None

    pond_union = (
        unary_union([z["polygon_utm"].buffer(POND_ZONE_EXCLUSION_BUFFER_METERS) for z in pond_zones])
        if pond_zones
        else None
    )

    exclusion_pieces = [
        u for u in (pond_union, hydric_floodplain_union, erosion_prone_union)
        if u is not None and not u.is_empty
    ]
    combined_exclusion_union = unary_union(exclusion_pieces) if exclusion_pieces else None
    excluded_prepared = prep(combined_exclusion_union) if combined_exclusion_union is not None else None
    boundary_prepared = prep(boundary_polygon_utm)
    excluded_mask = _build_exclusion_cell_mask(dem, excluded_prepared, boundary_prepared)

    raw_candidates: list[tuple[list[tuple[float, float, float]], str]] = []

    for cells in _generate_contour_band_cell_groups(
        dem, slope_pct, excluded_mask, max_grade_pct, CONTOUR_BAND_WIDTH_METERS, MIN_CONTOUR_BAND_CELLS
    ):
        centerline = _pca_centerline(cells, dem)
        if centerline:
            raw_candidates.append((centerline, "contour"))

    for run in _generate_ridge_candidate_runs(
        dem, slope_pct, excluded_mask, max_grade_pct, RIDGE_MIN_AREA_ACRES, RIDGE_MIN_PRIMARY_AREA_ACRES
    ):
        raw_candidates.append((run, "ridge"))

    scored = []
    for points, corridor_type in raw_candidates:
        anchored_points, is_arbitrary, anchor_road_name, anchor_road_distance_m = _anchor_to_boundary(
            points, boundary_polygon_utm, road_union_utm, road_features_utm
        )
        line = LineString([(p[0], p[1]) for p in anchored_points])

        length_m = line.length
        if length_m < min_corridor_length_meters:
            continue

        avg_grade_pct, grade_stddev_pct = _grade_stats(anchored_points)
        margin_m = (
            line.distance(combined_exclusion_union)
            if combined_exclusion_union is not None
            else EXCLUSION_MARGIN_REFERENCE_METERS
        )
        production_avoidance_score = _production_avoidance_score(line, raw_production_union)
        crosses_production_zone = raw_production_union is not None and line.intersects(raw_production_union)

        scored.append(
            {
                "corridor_type": corridor_type,
                "points_xyz": anchored_points,
                "line_utm": line,
                "length_m": length_m,
                "avg_grade_pct": avg_grade_pct,
                "grade_stddev_pct": grade_stddev_pct,
                "margin_m": margin_m,
                "production_avoidance_score": production_avoidance_score,
                "crosses_production_zone": crosses_production_zone,
                "connection_point_is_arbitrary": is_arbitrary,
                "anchor_road_name": anchor_road_name,
                "anchor_road_distance_m": anchor_road_distance_m,
            }
        )

    if not scored:
        return []

    longest_length_m = max(c["length_m"] for c in scored)
    for candidate in scored:
        candidate["suitability_score"] = _corridor_score(
            candidate["avg_grade_pct"],
            candidate["grade_stddev_pct"],
            candidate["margin_m"],
            candidate["length_m"],
            longest_length_m,
            max_grade_pct,
            candidate["production_avoidance_score"],
        )

    scored.sort(key=lambda c: -c["suitability_score"])
    scored = scored[:max_candidates]

    for rank, candidate in enumerate(scored, start=1):
        candidate["rank"] = rank
        xs = [p[0] for p in candidate["points_xyz"]]
        ys = [p[1] for p in candidate["points_xyz"]]
        lons, lats = warp_transform(dem["crs"], "EPSG:4326", xs, ys)
        candidate["geometry_wgs84"] = {"type": "LineString", "coordinates": list(zip(lons, lats))}

    return scored


def _confidence_notes_for_candidate(
    is_arbitrary_anchor: bool,
    anchor_road_name: Optional[str],
    floodplain_data_is_fallback: bool,
    erosion_data_unavailable: bool,
    avg_grade_pct: float,
    crosses_production_zone: bool,
) -> str:
    if is_arbitrary_anchor:
        anchor_note = (
            "an arbitrarily-chosen nearest point on the property boundary "
            "(no real road-frontage/access data was available to anchor to)"
        )
    elif anchor_road_name:
        anchor_note = f"the point on the property boundary nearest {anchor_road_name} (a real, mapped existing road)"
    else:
        anchor_note = "the point on the property boundary nearest a real, mapped existing road"

    production_crossing_note = PRODUCTION_CROSSING_NOTE if crosses_production_zone else ""

    steep_grade_note = (
        STEEP_GRADE_ENGINEERING_NOTE.format(
            avg_grade_pct=round(avg_grade_pct, 1), threshold_pct=STEEP_GRADE_ENGINEERING_NOTE_THRESHOLD_PCT
        )
        if avg_grade_pct > STEEP_GRADE_ENGINEERING_NOTE_THRESHOLD_PCT
        else ""
    )
    floodplain_note = (
        "Floodplain/wet-ground exclusion used a DEM-only fallback (buffered delineated valley "
        "lines), not real NHD/SSURGO data, because that data wasn't available for this run. "
        if floodplain_data_is_fallback
        else ""
    )
    erosion_note = (
        "Erosion-prone soil data (SSURGO K-factor) was not available for this run, so that "
        "exclusion was not applied. "
        if erosion_data_unavailable
        else ""
    )
    return ROAD_CORRIDOR_CONFIDENCE_NOTES_TEMPLATE.format(
        anchor_note=anchor_note,
        production_crossing_note=production_crossing_note,
        steep_grade_note=steep_grade_note,
        floodplain_note=floodplain_note,
        erosion_note=erosion_note,
    )


def corridors_to_geojson(
    candidates: list[dict],
    floodplain_data_is_fallback: bool = False,
    erosion_data_unavailable: bool = False,
) -> dict:
    """Wraps find_candidate_road_corridors() output as the schema-
    conformant GeoJSON FeatureCollection this feature delivers
    (layer="suggested_road_corridor")."""
    features = []
    for candidate in candidates:
        constraints_satisfied = [
            "outside_pond_zone",
            f"avg_grade<={MAX_ROAD_GRADE_PCT:.0f}pct",
        ]
        if not erosion_data_unavailable:
            constraints_satisfied.append("erosion_prone_soil_excluded")
        if not floodplain_data_is_fallback:
            constraints_satisfied.append("floodplain_hydric_excluded_via_nhd_ssurgo")
        else:
            constraints_satisfied.append("floodplain_excluded_via_elevation_fallback")

        anchor_road_distance_ft = (
            round(candidate["anchor_road_distance_m"] / METERS_PER_FOOT, 1)
            if candidate.get("anchor_road_distance_m") is not None
            else None
        )

        features.append(
            make_feature(
                feature_id=f"road-corridor-{candidate['corridor_type']}-{candidate['rank']}",
                geometry=candidate["geometry_wgs84"],
                layer="suggested_road_corridor",
                label=f"Suggested {candidate['corridor_type']} road corridor (rank {candidate['rank']})",
                confidence=CONFIDENCE_LOW,
                confidence_notes=_confidence_notes_for_candidate(
                    candidate["connection_point_is_arbitrary"],
                    candidate.get("anchor_road_name"),
                    floodplain_data_is_fallback,
                    erosion_data_unavailable,
                    candidate["avg_grade_pct"],
                    candidate["crosses_production_zone"],
                ),
                extra_properties={
                    "rank": candidate["rank"],
                    "suitability_score": round(candidate["suitability_score"] * 100, 1),
                    "corridor_type": candidate["corridor_type"],
                    "avg_grade_pct": round(candidate["avg_grade_pct"], 1),
                    "length_ft": round(candidate["length_m"] / METERS_PER_FOOT, 1),
                    "connection_point_is_arbitrary": candidate["connection_point_is_arbitrary"],
                    "anchor_road_name": candidate.get("anchor_road_name"),
                    "anchor_road_distance_ft": anchor_road_distance_ft,
                    "crosses_production_zone": candidate["crosses_production_zone"],
                    "constraints_satisfied": constraints_satisfied,
                },
            )
        )

    return make_feature_collection(features)


def _log_fetch_failure(label: str, exc: Exception) -> None:
    """
    Every real-data fetch in this module degrades gracefully on failure
    (see the module docstring), but "gracefully" shouldn't mean "silently
    identical whether the cause was a transient network timeout or a real
    bug in the query itself." A 4xx HTTP status means the server rejected
    the REQUEST as malformed (bad SQL, a column/table that doesn't exist)
    — that will fail exactly the same way on every future run, unlike a
    timeout or connection error, which might not. Anything that isn't
    even a requests error (a KeyError from an unexpected response shape,
    etc.) is just as clearly a real bug, not network flakiness. Print a
    distinct message for each case so this doesn't look like ordinary
    network unavailability in the logs — this is exactly how
    get_erosion_factor_for_polygon()'s chorizon/component schema bug went
    unnoticed for a while: it degraded identically to "SDA is slow today."
    """
    if isinstance(exc, requests.exceptions.RequestException):
        status = getattr(getattr(exc, "response", None), "status_code", None)
        if status is not None and 400 <= status < 500:
            print(
                f"  {label}: request rejected by the server (HTTP {status}) — likely a real "
                f"query/schema bug, not transient network unavailability: {exc}"
            )
        else:
            print(f"  {label}: network request failed ({exc}), continuing without it.")
    else:
        print(f"  {label}: unexpected failure, not a network error ({type(exc).__name__}: {exc}).")


def _fetch_floodplain_hydric_union(boundary_coordinates, dem, valleys) -> tuple[Optional[object], bool]:
    """NHD stream/water-body buffers + SSURGO hydric soil polygons,
    unioned; falls back to buffering the already-computed delineated
    valley lines (an elevation-only proxy) only if BOTH real sources are
    unreachable. Returns (union_or_None, is_fallback)."""
    pieces = []

    try:
        water_features = get_water_features_for_boundary(boundary_coordinates)
        for feature in water_features["streams"] + water_features["water_bodies"]:
            geometry = feature.get("geometry")
            if geometry is None:
                continue
            utm_geometry = shape(transform_geom("EPSG:4326", dem["crs"], geometry))
            pieces.append(utm_geometry.buffer(FLOODPLAIN_STREAM_BUFFER_METERS))
    except Exception as e:
        _log_fetch_failure("NHD stream/water-body fetch", e)

    try:
        wkt_polygon = coordinates_to_wkt_polygon(boundary_coordinates)
        soil_components = get_soil_data_for_polygon(wkt_polygon)
        hydric_mukeys = {c["mukey"] for c in soil_components if is_hydric(c.get("hydricrating"))}
        if hydric_mukeys:
            geometries_by_mukey = get_soil_geometries_for_polygon(wkt_polygon)
            for mukey in hydric_mukeys:
                geometry = geometries_by_mukey.get(mukey)
                if geometry is not None:
                    pieces.append(shape(transform_geom("EPSG:4326", dem["crs"], geometry)))
    except Exception as e:
        _log_fetch_failure("SSURGO hydric soil fetch", e)

    if pieces:
        return unary_union(pieces), False

    # Fallback: neither NHD nor SSURGO reachable -- use the valley network
    # already computed for pond-zone identification as a coarse,
    # elevation-only "probably wet ground follows drainage lines" proxy.
    fallback_pieces = []
    for valley in valleys:
        for branch in valley["branches_utm"]:
            line = LineString([(p[0], p[1]) for p in branch])
            fallback_pieces.append(line.buffer(FLOODPLAIN_STREAM_BUFFER_METERS))

    return (unary_union(fallback_pieces) if fallback_pieces else None), True


def _fetch_erosion_prone_union(boundary_coordinates, dem) -> tuple[Optional[object], bool]:
    """SSURGO K-factor-based erosion-prone soil union. Returns
    (union_or_None, data_unavailable) — data_unavailable is True only if
    the fetch itself failed, not if it succeeded and simply found no
    erosion-prone soil in the area."""
    try:
        wkt_polygon = coordinates_to_wkt_polygon(boundary_coordinates)
        erosion_rows = get_erosion_factor_for_polygon(wkt_polygon)
        erosion_prone_mukeys = {row["mukey"] for row in erosion_rows if is_erosion_prone(row.get("kwfact"))}
        if not erosion_prone_mukeys:
            return None, False

        geometries_by_mukey = get_soil_geometries_for_polygon(wkt_polygon)
        pieces = [
            shape(transform_geom("EPSG:4326", dem["crs"], geometries_by_mukey[mukey]))
            for mukey in erosion_prone_mukeys
            if mukey in geometries_by_mukey
        ]
        return (unary_union(pieces) if pieces else None), False
    except Exception as e:
        _log_fetch_failure("Erosion-prone soil (SSURGO K-factor)", e)
        return None, True


def _fetch_existing_road_features_utm(boundary_coordinates, dem) -> Optional[list[dict]]:
    """Real existing-road geometry WITH names (each {'name': str,
    'line_utm': LineString}), for anchor-road reporting (see
    _anchor_to_boundary's road_features_utm param and module docstring's
    "Corridor anchoring" section) — returns None on any failure or if
    nothing is nearby, which just leaves the eventual anchor's
    anchor_road_name generic/absent rather than raising."""
    try:
        roads = get_farm_roads_for_boundary(boundary_coordinates)
    except Exception as e:
        _log_fetch_failure("Existing road fetch", e)
        return None

    if not roads:
        return None

    features = []
    for road in roads:
        geometry = road["geometry"]
        line_lists = geometry["coordinates"] if geometry["type"] == "MultiLineString" else [geometry["coordinates"]]
        for line in line_lists:
            xs, ys = warp_transform("EPSG:4326", dem["crs"], [p[0] for p in line], [p[1] for p in line])
            features.append({"name": road["name"], "line_utm": LineString(zip(xs, ys))})

    return features if features else None


def _fetch_existing_road_union(boundary_coordinates, dem):
    """Real existing-road geometry, for anchoring only (see
    _anchor_to_boundary) — returns None on any failure or if nothing is
    nearby, which just makes anchoring fall back to an arbitrary boundary
    point rather than raising.

    UNCHANGED return shape (Optional[shapely geometry], no names) —
    scenario_generation.py imports and calls this directly for its own
    shared, per-report road fetch, and expects exactly this plain-union
    shape. identify_road_corridor_candidates() below no longer calls this
    (it uses _fetch_existing_road_features_utm() instead, to also get
    road names for anchor reporting without a second, redundant fetch);
    this stays as its own function purely for that external caller."""
    try:
        roads = get_farm_roads_for_boundary(boundary_coordinates)
    except Exception as e:
        _log_fetch_failure("Existing road fetch", e)
        return None

    if not roads:
        return None

    pieces = []
    for road in roads:
        geometry = road["geometry"]
        line_lists = geometry["coordinates"] if geometry["type"] == "MultiLineString" else [geometry["coordinates"]]
        for line in line_lists:
            xs, ys = warp_transform("EPSG:4326", dem["crs"], [p[0] for p in line], [p[1] for p in line])
            pieces.append(LineString(zip(xs, ys)))

    return unary_union(pieces) if pieces else None


def identify_road_corridor_candidates(
    boundary_coordinates: list[tuple[float, float]],
    dem: Optional[dict] = None,
    **corridor_kwargs,
) -> dict:
    """
    Full pipeline entry point: fetches/derives everything
    find_candidate_road_corridors() needs (production zones, pond zones,
    floodplain/hydric exclusion, erosion-prone soil exclusion, existing
    roads for anchoring) and returns the "suggested_road_corridor"
    GeoJSON FeatureCollection. Every real-data fetch degrades
    independently and gracefully, same pattern as
    water_candidate_zones.py and solar_suitability.py.
    """
    if dem is None:
        dem = get_dem_for_boundary(boundary_coordinates)

    boundary_xs, boundary_ys = warp_transform(
        "EPSG:4326",
        dem["crs"],
        [pt[0] for pt in boundary_coordinates],
        [pt[1] for pt in boundary_coordinates],
    )
    boundary_polygon_utm = Polygon(zip(boundary_xs, boundary_ys))

    production_areas = identify_production_areas(dem, boundary_polygon_utm)
    valleys = delineate_valleys(dem)  # reused for pond zones AND the floodplain fallback below

    pond_zones = find_pond_zones(valleys, production_areas, boundary_polygon_utm, dem["crs"])

    hydric_floodplain_union, floodplain_data_is_fallback = _fetch_floodplain_hydric_union(
        boundary_coordinates, dem, valleys
    )
    erosion_prone_union, erosion_data_unavailable = _fetch_erosion_prone_union(boundary_coordinates, dem)

    # One fetch (not two): _fetch_existing_road_features_utm() carries
    # both the per-feature list (for anchor_road_name reporting) and
    # everything needed to derive the plain union find_candidate_road_corridors()
    # actually anchors against -- deriving the union locally here avoids
    # a second, redundant get_farm_roads_for_boundary() call.
    road_features_utm = _fetch_existing_road_features_utm(boundary_coordinates, dem)
    road_union_utm = unary_union([f["line_utm"] for f in road_features_utm]) if road_features_utm else None

    candidates = find_candidate_road_corridors(
        dem,
        production_areas,
        pond_zones,
        boundary_polygon_utm,
        hydric_floodplain_union=hydric_floodplain_union,
        erosion_prone_union=erosion_prone_union,
        road_union_utm=road_union_utm,
        road_features_utm=road_features_utm,
        **corridor_kwargs,
    )

    return {
        "zones_geojson": corridors_to_geojson(
            candidates,
            floodplain_data_is_fallback=floodplain_data_is_fallback,
            erosion_data_unavailable=erosion_data_unavailable,
        )
    }


def summarize_road_corridor_candidates(result: dict) -> str:
    features = result["zones_geojson"]["features"]
    if not features:
        return "No suggested road corridor candidates identified (nothing cleared the constraint stack)."

    lines = [f"Suggested road corridor candidates: {len(features)}"]
    for feature in features:
        props = feature["properties"]
        if props["connection_point_is_arbitrary"]:
            anchor = " [arbitrary boundary anchor]"
        elif props.get("anchor_road_name"):
            anchor = f" [anchored to {props['anchor_road_name']}, {props.get('anchor_road_distance_ft')}ft]"
        else:
            anchor = " [anchored to a real road]"
        crossing = " [crosses production zone]" if props.get("crosses_production_zone") else ""
        lines.append(
            f"  - Rank {props['rank']} ({props['corridor_type']}): score {props['suitability_score']}/100, "
            f"{props['avg_grade_pct']}% avg grade, {props['length_ft']}ft{anchor}{crossing}"
        )
    return "\n".join(lines)


